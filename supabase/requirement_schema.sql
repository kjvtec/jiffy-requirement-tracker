-- ============================================================
-- Jiffy Requirement Tracker (New Pos Jiffy) - Database Schema
-- Idempotent: safe to run on a fresh project AND on top of the
-- previous version of this schema (it migrates in place).
-- ============================================================

-- 1. Running sequence for Req ID (JFY-REQ-01, 02, ...) -------------------
-- Assigned atomically by the database, so two people creating a
-- requirement at the same time can never collide on the same ID.
CREATE SEQUENCE IF NOT EXISTS public.requirement_seq START 1;

CREATE OR REPLACE FUNCTION public.next_req_id()
RETURNS TEXT AS $$
  SELECT 'JFY-REQ-' || lpad(nextval('public.requirement_seq')::text, 2, '0');
$$ LANGUAGE sql;

-- 2. requirements ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.requirements (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    req_id VARCHAR(50) UNIQUE NOT NULL DEFAULT public.next_req_id(),
    title VARCHAR(255) NOT NULL,
    priority VARCHAR(20) NOT NULL DEFAULT '2.Medium',
    type VARCHAR(50) NOT NULL DEFAULT 'New Feature',
    core_function VARCHAR(100) NOT NULL DEFAULT 'VTec POS',
    module VARCHAR(100) NOT NULL,
    details TEXT NOT NULL DEFAULT '',
    requested_by VARCHAR(100) NOT NULL,
    request_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    status VARCHAR(30) NOT NULL DEFAULT 'Draft',
    dev_assigned VARCHAR(100),
    target_version VARCHAR(50),
    remark TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Migrate tables created by the earlier schema version
ALTER TABLE public.requirements ALTER COLUMN req_id SET DEFAULT public.next_req_id();
ALTER TABLE public.requirements ALTER COLUMN details SET DEFAULT '';

-- Data integrity: only known values are accepted
ALTER TABLE public.requirements DROP CONSTRAINT IF EXISTS requirements_priority_check;
ALTER TABLE public.requirements ADD CONSTRAINT requirements_priority_check
    CHECK (priority IN ('1.High', '2.Medium', '3.Low'));

ALTER TABLE public.requirements DROP CONSTRAINT IF EXISTS requirements_status_check;
ALTER TABLE public.requirements ADD CONSTRAINT requirements_status_check
    CHECK (status IN ('Draft', 'In Review', 'In Development', 'Testing', 'Done'));

-- 3. requirement_images ---------------------------------------------------
CREATE TABLE IF NOT EXISTS public.requirement_images (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    requirement_id UUID NOT NULL REFERENCES public.requirements(id) ON DELETE CASCADE,
    file_url TEXT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_size INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. requirement_activity (history of status changes / comments) ----------
CREATE TABLE IF NOT EXISTS public.requirement_activity (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    requirement_id UUID NOT NULL REFERENCES public.requirements(id) ON DELETE CASCADE,
    actor VARCHAR(100) NOT NULL,
    action VARCHAR(30) NOT NULL,          -- created | status_change | comment | update
    from_status VARCHAR(30),
    to_status VARCHAR(30),
    message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. modules + team_members (used by the app, previously missing) ---------
CREATE TABLE IF NOT EXISTS public.modules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    core_function VARCHAR(100) NOT NULL,
    name VARCHAR(100) NOT NULL,
    UNIQUE (core_function, name)
);

CREATE TABLE IF NOT EXISTS public.team_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    role VARCHAR(100)
);

-- 6. Indexes ---------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_requirements_status ON public.requirements(status);
CREATE INDEX IF NOT EXISTS idx_requirements_priority ON public.requirements(priority);
CREATE INDEX IF NOT EXISTS idx_requirements_core_function ON public.requirements(core_function);
CREATE INDEX IF NOT EXISTS idx_requirements_module ON public.requirements(module);
CREATE INDEX IF NOT EXISTS idx_requirements_request_date ON public.requirements(request_date DESC);
CREATE INDEX IF NOT EXISTS idx_requirement_images_req_id ON public.requirement_images(requirement_id);
CREATE INDEX IF NOT EXISTS idx_requirement_activity_req_id ON public.requirement_activity(requirement_id, created_at DESC);

-- 7. Auto-update updated_at ------------------------------------------------
CREATE OR REPLACE FUNCTION public.update_requirement_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS set_requirements_updated_at ON public.requirements;
CREATE TRIGGER set_requirements_updated_at
BEFORE UPDATE ON public.requirements
FOR EACH ROW
EXECUTE FUNCTION public.update_requirement_updated_at();

-- 8. Row Level Security ----------------------------------------------------
-- NOTE: the app has no login (by design, internal team tool), so the anon
-- key is allowed full access. Anyone who knows the deployed URL can edit.
-- If that ever becomes a concern, switch these policies to
-- `TO authenticated` and add Supabase Auth.
ALTER TABLE public.requirements ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.requirement_images ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.requirement_activity ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.modules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.team_members ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all operations for requirements" ON public.requirements;
CREATE POLICY "Allow all operations for requirements" ON public.requirements FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all operations for requirement_images" ON public.requirement_images;
CREATE POLICY "Allow all operations for requirement_images" ON public.requirement_images FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all operations for requirement_activity" ON public.requirement_activity;
CREATE POLICY "Allow all operations for requirement_activity" ON public.requirement_activity FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all operations for modules" ON public.modules;
CREATE POLICY "Allow all operations for modules" ON public.modules FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all operations for team_members" ON public.team_members;
CREATE POLICY "Allow all operations for team_members" ON public.team_members FOR ALL USING (true) WITH CHECK (true);

