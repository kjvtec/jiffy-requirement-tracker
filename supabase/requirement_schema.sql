-- 13. Move the sequence past any existing JFY-REQ-nn rows -------------------
DO $$
DECLARE
    max_num INT;
    cur_val BIGINT;
BEGIN
    SELECT COALESCE(MAX(NULLIF(regexp_replace(req_id, '\D', '', 'g'), '')::int), 0)
      INTO max_num FROM public.requirements;
    SELECT CASE WHEN is_called THEN last_value ELSE 0 END
      INTO cur_val FROM public.requirement_seq;
    IF max_num > 0 AND max_num > cur_val THEN
        PERFORM setval('public.requirement_seq', max_num);
    END IF;
END $$;
